            string affValues = "NULL";
            if (alg.Affixes.Count > 0) {
               affValues = "(C2DataValue[]){"+string.Join(",",alg.Affixes.Select(aff => $"{affDiscriminator(aff)}({CName(aff)})"))+"}";
               //emitter.Emit("C2DataValue C2AffValues[] = {");
