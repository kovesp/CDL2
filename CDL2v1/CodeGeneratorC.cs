      public void GenerateAffixAndVariableInitializer(Algorithm alg,IFailureProtected item,bool isVar) {
         switch (item is Affix affix ? affix.affixDir : AD.transput) {
            case AD.NONE:
            case AD.input:
               break;
            case AD.output:
               if (isVar) {
                  emitter.Emitnl("VALUE ",TargetName((Var)item,"_")," = ",InitialValue,";");
               } else {
                  emitter.Emitnl("VALUE ",TargetName((Affix)item,"_")," = ",InitialValue,";");
               }
               break;
            case AD.transput:
               if (isVar) {
                  emitter.Emitnl("VALUE ",TargetName((Var)item,"_")," = ",TargetName((Var)item),";");
               } else {
                  emitter.Emitnl("VALUE ",TargetName((Affix)item,"_")," = *",TargetName((Affix)item),";");
               }
               break;
         }
      }

