      public void GenerateCallEnd(Algorithm called,Procedure calling,bool canFail,bool onlyCallInAlternative,bool lastAlternative) {
         if (called.CanFail) {
            if (lastAlternative) {
               emitter.Emit(")) RETURNV(FALSE);");
            } else {
               ReferencedLabels.Add(Label);
               emitter.Emit($")) goto {Label};");
            }
         } else {
            emitter.Emit(");");
         }
         Newline();
      }

