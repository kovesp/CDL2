         int i => i.ToString(),
         double d => d.ToString(System.Globalization.CultureInfo.InvariantCulture),
         string s => $"\"{s.Replace("\"","`\"")}\"",
         _ => throw new NotImplementedException($"Value expression generation not implemented for type {value.GetType()}."),
      };

