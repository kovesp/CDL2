            }
            string localValues = "NULL";
            if (locals.Any()) {
               localValues = "(VALUE[]){" + string.Join(",",alg.Locals.Select(loc => $"{CName(loc)}")) + "}";
            //   emitter.Emit("VALUE* C2Locals[] = {");
