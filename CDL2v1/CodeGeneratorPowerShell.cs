      public void GenerateAlgorithmHeaderEnd(Algorithm proc) {
         emitter.Emitnl(") {");
         emitter.IndentLevel++;
      }

      public void GenerateStart(Procedure code) { }
      public void GenerateEnd(Procedure proc) {
         if (proc.CanFail) emitter.Emitnl("return $__b");
         emitter.IndentLevel--;
         emitter.NlEmitnl("}");
      }

