      private static readonly string ProgramHeaderPattern = @"
<#
.SYNOPSIS
   PowerShell proc generated by CDL2 notLastAlternativeOfProc<%0%> for Program <%1%> at <%2:yyyy-MM-dd HH:mm:ss%>.
#>
class BoundedArray {
   [int]$LowerBound
   [int]$UpperBound
   [Array]$Array
   

   BoundedArray([int]$lowerBound, [int]$upperBound) {
       if ($upperBound - $lowerBound -lt 0) {
           throw [System.ArgumentException]::new(""Upper bound $($this.UpperBound) must be greater than or equal to lower bound $($this.LowerBound)."")
       }
       $this.LowerBound = $lowerBound
       $this.UpperBound = $upperBound
       $this.Array = [<%3%>[]]::new($upperBound - $lowerBound + 1)
   }
   [void]CheckIndex([int]$index) {
      if ($index - $this.LowerBound -ge 0 -and $index - $this.LowerBound -le $this.UpperBound - $this.LowerBound) {
         return
      } else {
         throw [System.IndexOutOfRangeException]::new(""Index: $index, LowerBound: $($this.LowerBound), UpperBound: $($this.UpperBound)"")
       }
   }
   # These do NOT create a [] indexer
   [<%3%>]Item([int]$index) {
      $this.CheckIndex($index)
      return $this.Array[$index - $this.LowerBound]
   }

   [void]Item([int]$index, [<%3%>]$value) {
      $this.CheckIndex($index)
      $this.Array[$index - $this.LowerBound] = $value
   }
}

#===============================================================================
";
      private static readonly string ProgramHeader;

      static CodeGeneratorPowerShell() => ProgramHeader = ProgramHeaderPattern.Replace("{","{{").Replace("}","}}").Replace("<%","{").Replace("%>","}");

      public void GenerateComment(string comment) {
         foreach (string line in comment.Split('\n')) emitter.Emitnl("# ",line);
      }

      public void GenerateStart(Program program,EmitterBase emitter) {
         this.emitter = emitter;
         emitter.Emitnl(string.Format(ProgramHeader,CDL2.Version,program.id.Name,DateTime.Now,DataType));


         if (program != null) EmitUnitStartComment(program);
      }

      public void GenerateEnd(Program program) {
         if (program != null) EmitUnitEndComment(program);
      }
      public void GenerateStart(Module module) => EmitUnitStartComment(module);
      public void GenerateEnd(Module module) => EmitUnitEndComment(module);
      public void GenerateStart(Layer layer) => EmitUnitStartComment(layer);
      public void GenerateEnd(Layer layer) => EmitUnitEndComment(layer);
      public void GenerateStart(Section section) => EmitUnitStartComment(section);
      public void GenerateEnd(Section section) => EmitUnitEndComment(section);

      enum PSVarType { Var, List, Const, Affix, Local }

      private static string PSVarPrefix(PSVarType type) => type switch {
         PSVarType.Var => "V_",
         PSVarType.List => "LL_",
         PSVarType.Const => "C_",
         PSVarType.Affix => "A_",
         PSVarType.Local => "L_",
         _ => throw new NotImplementedException(),
      };
      private static PSVarType PSVarTypeOf(DeclaredCDL2Object obj) => obj switch {
         Var => PSVarType.Var,
         LIST => PSVarType.List,
         Const => PSVarType.Const,
         _ => throw new NotImplementedException(),
      };

      private static string _PSVar(string name,PSVarType type,string prefix = "",string suffix = "") => $"${prefix}{PSVarPrefix(type)}{name}{suffix}";
      private static string PSVar(DeclaredCDL2Object obj,string prefix = "",string suffix = "") => _PSVar(PSName(obj),PSVarTypeOf(obj),prefix,suffix);
      private static string PSVar(Affix affix,string prefix = "",string suffix = "") => _PSVar(PSName(affix),PSVarType.Affix,prefix,suffix);
      private static string PSVar(Local local,string prefix = "",string suffix = "") => _PSVar(PSName(local),PSVarType.Local,prefix,suffix);

      private static string PSName(DeclaredCDL2Object obj) => obj.FQN(camelCase: true,literalObjectName:obj.IsSynthetic);
      private static string PSName(Affix affix) => affix.id.Name.AsIdentifier(camelCase:true);
      private static string PSName(Local local) => local.id.Name.AsIdentifier(camelCase: true);
      //private static string PSName(NamedElement name) => name.AsName();

      public void GenerateCode(Const c) {
         string value = $"{PSVar(c)} = ";
         foreach (IConstElement e in c.elements) {
            value += e switch {
               STRING s => $"\"{s.value}\"",
               INT n => n.value,
               FLOAT f => f.value,
               Const ce => PSVar(ce),
               //ID id    => PSVar(id),
               _ => throw new NotImplementedException(),
            };
         }
         emitter.Emitnl(value);
      }
      public void GenerateCode(Var v) => emitter.Emitnl($"{PSVar(v)}");
      public void GenerateCode(LIST l,string lwb,string upb) => emitter.Emitnl($"{PSVar(l)} = New-Object BoundedArray {lwb} {upb}");

