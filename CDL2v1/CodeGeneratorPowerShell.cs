      public void GenerateLudeEnd(RW ludeType,Container section) => throw new NotImplementedException();
      public void GenerateStart(Macro macro) { }
      public void GenerateEnd(Macro macro) {
         emitter.IndentLevel--;
         emitter.NlEmitnl("}");
