namespace CDL2v1 {
   [Serializable]
   internal class CodeGeneratorPowerShell : ICodeGenerator {
      #region Instance and Static Varibles, Constructors
      EmitterBase emitter = new EmitterSink();
      private readonly string DataType;
      private readonly string DT;

      /// <summary>
      /// Constructor for the PowerShell proc generator.
      /// </summary>
      /// <param name="dataType">This can be used to change the word size, e.g., to Int32.</param>
      /// <remarks>No explicit references to this class. The instance is constructed via reflection.</remarks>
      public CodeGeneratorPowerShell(string dataType) {
         DataType = dataType;
         DT       = $"[{DataType}]";
      }

      private static readonly string ProgramHeaderPattern = @"
#cspell:disable
<#
.SYNOPSIS
   PowerShell program generated by CDL2 typeName<%0%> for PROGRAM <%1%> at <%2:yyyy-MM-dd HH:mm:ss%>.
#>
class BoundedArray {
   [int]$LowerBound
   [int]$UpperBound
   [Array]$Array
   

   BoundedArray([int]$lowerBound, [int]$upperBound) {
       if ($upperBound - $lowerBound -lt 0) {
           throw [System.ArgumentException]::new(""Upper bound $($this.UpperBound) must be greater than or equal to lower bound $($this.LowerBound)."")
       }
       $this.LowerBound = $lowerBound
       $this.UpperBound = $upperBound
       $this.Array = [<%3%>[]]::new($upperBound - $lowerBound + 1)
   }
   [void]CheckIndex([int]$index) {
      if ($this.LowerBound -le $index -and $index -le $this.UpperBound) {
         return
      } else {
         throw [System.IndexOutOfRangeException]::new(""Index: $index, LowerBound: $($this.LowerBound), UpperBound: $($this.UpperBound)"")
       }
   }
   # These do NOT create a [] indexer
   [<%3%>]Item([int]$index) {
      $this.CheckIndex($index)
      return $this.Array[$index - $this.LowerBound]
   }

   [void]Item([int]$index, [<%3%>]$value) {
      $this.CheckIndex($index)
      $this.Array[$index - $this.LowerBound] = $value
   }
}

function Set-Const([string]$name,[<%3%>]$value) {
   Set-Variable -Name $name -Value $value -Option ReadOnly -Force -Scope Script
}
function Remove-Const([string[]]$names) {
   Set-Variable -Name $names -Option None -Force -Scope Script
}

#===============================================================================
";
      private static readonly string ProgramHeader;

      static CodeGeneratorPowerShell() => ProgramHeader = ProgramHeaderPattern.Replace("{","{{").Replace("}","}}").Replace("<%","{").Replace("%>","}");
      #endregion Instance and Static Varibles, Constructors

      #region Programs, Modules, Layers, Sections
      void ICodeGenerator.GenerateProgramStart(Program program,EmitterBase emitter,bool isSeparate) {
         this.emitter = emitter;
         emitter.Emitnl(string.Format(ProgramHeader,CDL2.Version,program.id.Name,DateTime.Now,DataType));
         if (program != null) EmitUnitStartComment(program);
      }
      void ICodeGenerator.GenerateProgramPart(Program program,ID mod,bool isSeparate) { }

      void ICodeGenerator.GenerateProgramEnd(Program program,bool isSeparate) {
         if (program != null) EmitUnitEndComment(program);
      }
      void ICodeGenerator.GenerateModuleStart(Module module,bool isSeparate,string? target) {
         if (isSeparate) {
            // Changes the target file name to be the module name with the extension. Ignored by emitters except for the file Emitter.
            // This causes the file Emitter to close the current file and switch to the new file.
            emitter.Target = Path.Combine(Path.GetDirectoryName(emitter.Target)??"",module.id.InternalName+((ICodeGenerator)this).FileExtension);
         }
         EmitUnitStartComment(module);
      }
      void ICodeGenerator.GenerateModuleEnd(Module module,bool isSeparate) => EmitUnitEndComment(module);
      void ICodeGenerator.GenerateLayerStart(Layer layer) => EmitUnitStartComment(layer);
      void ICodeGenerator.GenerateLayerEnd(Layer layer) => EmitUnitEndComment(layer);
      void ICodeGenerator.GenerateSectionStart(Section section) => EmitUnitStartComment(section);
      void ICodeGenerator.GenerateSectionEnd(Section section) => EmitUnitEndComment(section);

      #endregion Programs, Modules, Layers, Sections

      #region Predlude, Postlude, Root
      void ICodeGenerator.GenerateProgramLudeStart(RW ludetype, Program program) {
         GenerateComment($"{program.TypeShortName}_{program.id.Name.AsIdentifier(camelCase: true)}_{ludetype}");
         emitter.IndentLevel++;
      }
      void ICodeGenerator.GenerateProgramLude(RW ludeType, Program program, Module module)
         => emitter.Emitnl($"{module.TypeShortName}_{module.id.Name.AsIdentifier(camelCase: true)}_{ludeType}");
      void ICodeGenerator.GenerateProgramLudeEnd(RW ludeType, Program program) {
         emitter.IndentLevel--;
      }

      void ICodeGenerator.GenerateModuleLudeStart(RW ludetype, Module module, bool wrapped) {
         string moduleName = $"{module.TypeShortName}_{module.id.Name.AsIdentifier(camelCase: true)}_{ludetype}";
         if (wrapped) {
            emitter.Emitnl($"function {moduleName} {{");
         } else {
            emitter.Emitnl($" # {moduleName}");
         }
         emitter.IndentLevel++;
      }
      void ICodeGenerator.GenerateModuleLude(RW ludeType, Module module, Section section)
         => emitter.Emitnl(section.SyntheticProcedures.Where(p=>p.id.InternalName == ludeType.ToString()).FirstOrDefault()?.FQN(camelCase: true, literalObjectName:true)!);
      void ICodeGenerator.GenerateModuleLudeEnd(RW ludeType, Module module, bool wrapped) {
         emitter.IndentLevel--;
         if (wrapped) emitter.Emitnl("}");
      }

      void ICodeGenerator.GenerateSectionLudeStart(RW ludeType,Section section) => throw new NotImplementedException();
      void ICodeGenerator.GenerateSectionLudeEnd(RW ludeType,Section section) => throw new NotImplementedException();
      #endregion Predlude, Postlude, Root

      #region Impport/Export
      void ICodeGenerator.GenerateImpExStart(Module module) { }
      void ICodeGenerator.GenerateImpExEnd(Module module) { }
      void ICodeGenerator.GenerateExport(IProvidedElement export) { }
      void ICodeGenerator.GenerateImport(IProvidedElement import) { }
      #endregion Import/Export

      #region Object Sections
      void ICodeGenerator.GenerateObjectSectionStart<T>(IEnumerable<NamedElement> items, string typeName) {
         int n = items.Count();
         if (n > 0) {
            emitter.NlEmitnl($"\n##### {n} {typeName}{(n != 1 ? "s" : "")} #####\n");
            if (items.First() is Const) {
               emitter.Emitnl("Remove-Const ",string.Join(",",items.Select(c=>PSVarPrefix(PSVarType.Const)+PSName((c as Const)!))));
            }
         }
      }
      void ICodeGenerator.GenerateObjectSectionEnd<T>(IEnumerable<NamedElement> items,string typeName) { }
      #endregion Object Sections

      #region Data Declarations
#if WantsRealConstants
      void ICodeGenerator.GenerateConstantStart(Const c) => emitter.Emit("Set-Variable -Option Constant -Name '", PSName(c), "' -Value ");
#else
      /// <summary>
      /// Generates the start of a constant declaration.
      /// Use this version to get constants that can be modifieed
      /// </summary>
      /// <param name="c"></param>
      void ICodeGenerator.GenerateConstantStart(Const c) => emitter.Emit(PSVar(c), " = 0; Set-Const '",PSVarPrefix(PSVarType.Const),PSName(c),"' ");
#endif


      // Set-Variable -Name MyConstant -Value 42 -Option Constant
      void ICodeGenerator.GenerateConstElementString(string value) => ((ICodeGenerator)this).GenerateMacroElementString(value, false, false);
      void ICodeGenerator.GenerateConstElementFloat(double value) => ((ICodeGenerator)this).GenerateMacroElementFloat(value);
      void ICodeGenerator.GenerateConstElementInt(long value) => ((ICodeGenerator)this).GenerateMacroElementInt(value);
      void ICodeGenerator.GenerateConstElementConst(Const constant) => emitter.Emit(PSVar(constant));
      void ICodeGenerator.GenerateConstantEnd(Const c) => emitter.Emitnl();
      void ICodeGenerator.GenerateVar(Var var) => emitter.Emitnl(DT, PSVar(var), " = ", RandomInitialValue);

      void ICodeGenerator.GenerateList(LIST var, Const lwb, Const upb) => emitter.Emitnl(PSVar(var), $" = [BoundedArray]::new({PSVar(lwb)},{PSVar(upb)})");
      #endregion Data Declarations

      #region Algorithm Common
      void ICodeGenerator.GenerateAlgorithmHeaderStart(Algorithm proc) => emitter.Emit($"function {PSName(proc)}(");
      void ICodeGenerator.GenerateAlgorithmHeaderEnd(Algorithm proc) {
         emitter.Emitnl(") {");
         emitter.IndentLevel++;
      }
      void ICodeGenerator.GenerateAffixSeparator() => emitter.Emit(",");
      /// <summary>
      /// Locals are initialized to a random value to ensure that they are not used before being set.
      /// The latter should be made impossible by semantic analysis.
      /// </summary>
      /// <param name="local"></param>
      void ICodeGenerator.GenerateLocal(Local local) => emitter.Emitnl(DT, PSVar(local), " = ",RandomInitialValue);
      void ICodeGenerator.GenerateAffix(Affix affix, AD dir, bool algorithmCanFail) {
         switch (dir) {
            case AD.input:
               emitter.Emit(DT, PSVar(affix));
               break;
            case AD.NONE:
               // String (given as AD.NONE)
               emitter.Emit("[string]", PSVar(affix));
               break;
            default: // input or transput
               emitter.Emit("[ref]", PSVar(affix));
               break;
         }
      }

      void ICodeGenerator.GenerateAffixAndVariableInitializer(Algorithm alg, IFailureProtected var, bool isVar) {
         switch (var is Affix affix ? affix.affixDir : AD.transput) {
            case AD.NONE:
            case AD.input:
               break;
            case AD.output:
               // The output shadow is initialized to a random value to ensure that it is set before use.
               if (isVar) {
                  emitter.Emitnl(DT, PSVar((Var)var, "_"), " = ", RandomInitialValue);
               } else {
                  emitter.Emitnl(DT, PSVar((Affix)var, "_"), " = ", RandomInitialValue);
               }
               break;
            case AD.transput:
               if (isVar) {
                  emitter.Emitnl(DT, PSVar((Var)var, "_"), " = ", PSVar((Var)var));
               }
               else {
                  emitter.Emitnl(DT, PSVar((Affix)var, "_"), " = ", PSVar((Affix)var, suffix: ".Value"));
               }
               break;
         }
      }
      void ICodeGenerator.GenerateAffixAndVariableInitializationStart(Algorithm alg) { }

      void ICodeGenerator.GenerateAffixAndVariableInitializationEnd(Algorithm alg) { }
      void ICodeGenerator.GenerateAffixAndVariableFinalizationStart(Algorithm algorithm, bool IsNeeded) {
         if (IsNeeded && algorithm.CanFail) {
            emitter.Emitnl("if ($__b) {");
            emitter.IndentLevel++;
         }
      }
      void ICodeGenerator.GenerateAffixAndVariableFinalizationEnd(Algorithm algorithm, bool IsNeeded) {
         if (IsNeeded && algorithm.CanFail) {
            emitter.IndentLevel--;
            emitter.Emitnl("}");
         }
      }

      void ICodeGenerator.GenerateAffixAndVariableFinalizer(Algorithm alg, IFailureProtected var, bool isVar) {
         switch (var is Affix affix ? affix.affixDir : AD.transput) {
            case AD.NONE:
            case AD.input:
               break;
            default:
               if (isVar) {
                  emitter.Emitnl(PSVar((Var)var), " = ", PSVar((Var)var, "_"));
               }
               else {
                  emitter.Emitnl(PSVar((Affix)var, suffix: ".Value"), " = ", PSVar((Affix)var, "_"));
               }
               break;
         }
      }
      #endregion Algorithm Common

      #region Macros
      void ICodeGenerator.GenerateMacroStart(Macro macro) { }
      void ICodeGenerator.GenerateMacroEnd(Macro macro) {
         if (macro.CanFail && HasMultipleStatments(macro)) emitter.Emitnl("$__b");
         emitter.IndentLevel--;
         emitter.NlEmitnl("}");
      }

      void ICodeGenerator.GenerateMacroElementInt(long value) => emitter.Emit(value);
      void ICodeGenerator.GenerateMacroElementFloat(double value) => emitter.Emit(value);
      void ICodeGenerator.GenerateMacroElementString(string value, bool canFail, bool firstElement) {
         string[] lines = value.Split('\n');
         foreach (string line in lines.Skip(firstElement ? 1 : 0).SkipLast(1)) emitter.Emitnl(line);
         emitter.Emit(lines.Last());
      }
      void ICodeGenerator.GenerateMacroElementVar(Var var, bool macroCanFail) => emitter.Emit(PSVar(var, macroCanFail ? "_" : ""));
      void ICodeGenerator.GenerateMacroElementList(LIST list) => emitter.Emit(PSVar(list));
      void ICodeGenerator.GenerateMacroElementConst(Const constant) => emitter.Emit(PSVar(constant));
      void ICodeGenerator.GenerateMacroElementAffix(Affix affix, bool macroCanFail) {
         if (affix.IsOutput) {
            emitter.Emit(PSVar(affix, macroCanFail ? "_" : "", macroCanFail ? "" : ".Value"));
         }
         else {
            emitter.Emit(PSVar(affix));
         }
      }
      void ICodeGenerator.GenerateMacroElementLocal(Local local) => emitter.Emit(PSVar(local));

      void ICodeGenerator.GenerateMacroBodyStart(Macro macro) {
         if (macro.NeedsFinalization) emitter.IndentLevel++;
         if (macro.CanFail && HasMultipleStatments(macro)) {
            emitter.Emitnl("$__b = @(");
            emitter.IndentLevel++;
         }
      }
      void ICodeGenerator.GenerateMacroBodyEnd(Macro macro) {
         if (macro.CanFail && HasMultipleStatments(macro)) {
            emitter.IndentLevel--;
            emitter.NlEmitnl(")[-1]");
         }
         if (macro.NeedsFinalization) emitter.IndentLevel--;
      }
      private static bool HasMultipleStatments(Macro macro) => macro.elements.OfType<STRING>().Any(str => Regex.IsMatch(str.value, @"(?<!['""])(?:\n|;)(?![^'""]*['""])",RegexOptions.Compiled));

      #endregion Macros

      #region Procedures
      void ICodeGenerator.GenerateProcedureStart(Procedure code) { }
      void ICodeGenerator.GenerateProcedureEnd(Procedure proc) {
         if (proc.CanFail) emitter.Emitnl("return $__b");
         emitter.IndentLevel--;
         emitter.NlEmitnl("}");
      }
      void ICodeGenerator.GenerateProcedureBodyStart(Procedure proc,PBT bodyType) {
         if (proc.repeatsProcedure) emitter.Emit(":",proc.id.InternalName," ");
         //TODO: The needs finalization test for enclosing do { } while ($true) is likely wrong.
         if (!proc.IsVerySimple || proc.NeedsFinalization) emitter.Emitnl("do {");
         emitter.IndentLevel++;
      }
      void ICodeGenerator.GenerateProcedureBodyEnd(Procedure proc,PBT bodyType) {
         if (proc.NeedsFinalization) emitter.Emitnl("break");
         emitter.IndentLevel--;
         if (!proc.IsVerySimple || proc.NeedsFinalization) emitter.Emitnl("} while ($true)");
      }
      #region Alternatives
      void ICodeGenerator.GenerateAlternativeStart(Procedure proc,Group group,int i) {
         GenerateComment($"Alternative {i+1}");
         emitter.IndentLevel++;
      }
      void ICodeGenerator.GenerateAlternativeEnd(Procedure proc,Group group,int i, bool removed) {
         bool notLastAlternativeOfProc = group != proc.group || group.alternatives.Count != i + 1;
         if (notLastAlternativeOfProc) {
            if (removed) {
               // Just fall through to the next alternative
            } else if (proc.NeedsFinalization) {
               Debug.Assert(proc.CanFail, $"{proc} needs finalization but cannot fail???");
               emitter.Emitnl("if ($__b) { break }");
            }
            else {
               if (proc.CanFail) {
                  emitter.Emitnl("if ($__b) { return $true }");
               }
               else {
                  emitter.Emitnl("return");
               }
            }
         } else if (group.alternatives[^1].CanFail) {
            if (proc.NeedsFinalization) {
               Debug.Assert(proc.CanFail, $"{proc} needs finalization but cannot fail???");
               emitter.Emitnl("break");
            } else if (proc.CanFail) {
               emitter.Emitnl("return $true");
            } else {
               emitter.Emitnl("return");
            }
         } else if (proc.NeedsFinalization) {
            Debug.Assert(proc.CanFail, $"{proc} needs finalization but cannot fail???");
            emitter.Emitnl("$__b = $true; break");
         } else if (proc.CanFail) {
            emitter.Emitnl("return $true");
         } else {
            emitter.Emitnl("return");
         }
         emitter.IndentLevel--;
      }
      /// <summary>
      /// Generates the fail required when the rest of an alternative is discarded due to conditional compilation.
      /// </summary>
      void ICodeGenerator.GenerateAlternativeFail() => emitter.Emitnl("$__b = $false");
      #endregion Alternatives

      #region Groups
      void ICodeGenerator.GenerateGroupStart(Procedure proc,Group group) {
         if (!group.IsSynthetic) emitter.Emit(":",group.id.InternalName," ");
         emitter.Emitnl("do {");
         emitter.IndentLevel++;
      }
      void ICodeGenerator.GenerateGroupEnd(Procedure proc,Group group) {
         emitter.IndentLevel--;
         emitter.Emitnl("} while ($true)");
      }
      #endregion Groups

      #region Calls
      void ICodeGenerator.GenerateCallEnd(Call call) => throw new NotImplementedException();
      void ICodeGenerator.GenerateCallStart(Call call) => throw new NotImplementedException();
      void ICodeGenerator.GenerateActualArgSeparator() => emitter.Emit(" ");
      void ICodeGenerator.GenerateCallStart(Algorithm called,Procedure proc,bool canFail) {
         if (!proc.IsVerySimple) {
            if (canFail) emitter.Emit("if ($__b) { ");
            if (called.CanFail) {
               if (canFail) {
                  emitter.Emit("$__b = ");
               } else {
                  emitter.Emit("[bool]$__b = ");
               }
            }
         }
         emitter.Emit(PSName(called)," ");
      }
      void ICodeGenerator.GenerateCallEnd(Algorithm call,Procedure proc,bool canFail) {
         if (canFail && !proc.IsVerySimple) {
            emitter.Emit(" }");
         }
         Newline();
      }

      void ICodeGenerator.GenerateCallArgString(string value) => emitter.Emit($"\"{value}\"");
      void ICodeGenerator.GenerateCallArgReferenceAffix(Affix calledAffix, Affix a, bool needFinalization) 
         => emitter.Emit(PSVar(a, needFinalization ? "_": "",isRef:calledAffix.IsOutput));
      void ICodeGenerator.GenerateCallArgReferenceLocal(Affix calledAffix,Local lo) => emitter.Emit(PSVar(lo,isRef: calledAffix.IsOutput));
      void ICodeGenerator.GenerateCallArgReferenceConst(Affix calledAffix,Const c) => emitter.Emit(PSVar(c));
      void ICodeGenerator.GenerateCallArgReferenceVar(Affix calledAffix, Var v, bool needFinalization) 
         => emitter.Emit(PSVar(v, needFinalization ? "_" : "", isRef: calledAffix.IsOutput));

      void ICodeGenerator.GenerateRepeat(Procedure proc,Group group,ID label) {
         // TODO: Needs more work to ensure labels are unique within a proc
         if (label == ID.AnonID) {
            emitter.Emitnl("if ($__b) { continue }");
         } else {
            emitter.Emitnl("if ($__b) { continue ",label.InternalName," }");
         }
      }
      void ICodeGenerator.GenerateFail(Procedure proc,Group group) {
         if (!proc.IsVerySimple) {
            emitter.Emitnl(proc.CanFail ? "if ($__b) { return $false }" : "return");
         }
      }
      void ICodeGenerator.GenerateSucceed(Procedure proc, Group group) {
         if (proc.CanFail) {
            emitter.Emitnl("return $true");
         } else {
            emitter.Emitnl("return");
         }
      }
      void ICodeGenerator.GenerateAbort(Procedure proc,Group group) => emitter.Emitnl("exit 1");
      #endregion Calls

      #endregion Procedures

      #region Support
      void ICodeGenerator.GenerateNewline() => Newline();
      void ICodeGenerator.GenerateComment(string comment) => GenerateComment(comment);
      void ICodeGenerator.GenerateComment(PrettyPrinter pp) => emitter.Emit(pp.Emitter.Content);
      void ICodeGenerator.GenerateSourceComment() => emitter.Emit(sourceEmitter.Content);
      string ICodeGenerator.FileExtension { get; } = ".ps1";

      private readonly EmitterString sourceEmitter = new(prefix:"# ");
      EmitterBase ICodeGenerator.SourceEmitter => sourceEmitter;
      #endregion Support

      #region Helpers
      void Newline() => emitter.Emitnl();
      private void EmitUnitStartComment(Container unit) => emitter.Emitnl($"# Begin {unit.ContainerName}");
      private void EmitUnitEndComment(Container unit) => emitter.Emitnl($"# End {unit.ContainerName}");
      private void GenerateComment(string comment) {
         foreach (string line in comment.Split('\n')) emitter.Emitnl("# ",line);
      }
      enum PSVarType { Var, List, Const, Affix, Local }

      private static string PSVarPrefix(PSVarType type) => type switch {
         PSVarType.Var => "V_",
         PSVarType.List => "LL_",
         PSVarType.Const => "C_",
         PSVarType.Affix => "A_",
         PSVarType.Local => "L_",
         _ => throw new NotImplementedException(),
      };
      private static PSVarType PSVarTypeOf(DeclaredCDL2Object obj) => obj switch {
         Var => PSVarType.Var,
         LIST => PSVarType.List,
         Const => PSVarType.Const,
         _ => throw new NotImplementedException(),
      };

      private static string PS_Var(string name,PSVarType type,string prefix = "",string suffix = "",bool isRef = false) 
         => $"{(isRef ? "([ref]" : "")}${prefix}{PSVarPrefix(type)}{name}{suffix}{(isRef ? ")" : "")}";
      private static string PSVar(DeclaredCDL2Object obj,string prefix = "",string suffix = "",bool isRef = false) => PS_Var(PSName(obj),PSVarTypeOf(obj),prefix,suffix,isRef);
      private static string PSVar(Affix affix,string prefix = "",string suffix = "",bool isRef = false) => PS_Var(PSName(affix),PSVarType.Affix,prefix,suffix,isRef);
      private static string PSVar(Local local,string prefix = "",string suffix = "",bool isRef = false) => PS_Var(PSName(local),PSVarType.Local,prefix,suffix,isRef);

      private static string PSName(DeclaredCDL2Object obj) => obj.FQN(camelCase: true,literalObjectName: obj.IsSynthetic);
      private static string PSName(Affix affix) => affix.id.Name.AsIdentifier(camelCase: true);
      private static string PSName(Local local) => local.id.Name.AsIdentifier(camelCase: true);


      private static readonly Random Random = new();
      private static string RandomInitialValue => Random.Next(0, int.MaxValue).ToString()+"  <# Random value to catch uninitialized VARs, LOCALs, and output AFFIXes #>";
      #endregion Helpers
   }
