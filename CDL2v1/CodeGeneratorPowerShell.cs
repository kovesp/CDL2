      private ModifiableStack ifDepth = [];
      void ICodeGenerator.GenerateProcedureStart(Procedure code) {
         ifDepth.Push(0);
      }
      void ICodeGenerator.GenerateProcedureEnd(Procedure proc) {
         ifDepth.Pop();
         emitter.Emitnl(proc.CanFail ? proc.NeedsFinalization ? "return $true" : "return $false" : "return");
         DecrementIndent();
         emitter.NlEmitnl("}");
      }
      void ICodeGenerator.GenerateProcedureBodyStart(Procedure proc,PBT bodyType) {
         if (proc.NeedsWrapper) {
            emitter.Emitnl(":",proc.Id.CanonicalName," do {");
            IncrementIndent();
         }
      }

      private static bool NeedsWrapper(Procedure proc) => proc.repeatsProcedure || proc.NeedsFinalization || proc.HasRepeat;

      void ICodeGenerator.GenerateProcedureBodyEnd(Procedure proc,PBT bodyType) {
         if (proc.NeedsWrapper) {
            emitter.Emitnl(proc.CanFail ? "return $false" : "return");
            DecrementIndent();
            emitter.Emitnl("} while ($true)");
         }
      }

      #region Alternatives
      void ICodeGenerator.GenerateAlternativeStart(Procedure proc,Group group,int alternativeNumber,bool suppressLabel) 
         => GenerateComment($"Alternative {alternativeNumber}");
      void ICodeGenerator.GenerateAlternativeEnd(Procedure proc,Group group,int i,Alternative alternative,bool removed) {
         if (alternative.lastCall.type != LCT.Group && alternative.lastCall.type != LCT.Repeat && !removed && !alternative.Terminates)
            emitter.Emitnl(proc.CanFail ? (proc.NeedsWrapper ? $"break {proc.Id.CanonicalName}" : "return $true") : "return");
         while (ifDepth > 0) {
            DecrementIndent();
            ifDepth--;
            emitter.Emitnl("}");
         }
         GenerateComment($"End Alternative {i}");
      }

