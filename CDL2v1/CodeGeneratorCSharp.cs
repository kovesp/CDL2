      void ICodeGenerator.GenerateAffixAndVariableInitializer(Algorithm alg,IFailureProtected var,bool isVar) {
         switch (var is Affix affix ? affix.affixDir : AD.transput) {
            case AD.NONE:
            case AD.input:
               break;
            case AD.output:
               if (isVar) {
                  emitter.Emitnl(DataType," ",TargetName((Var)var,"_")," = ",InitialValue,";");
               } else {
                  emitter.Emitnl(DataType," ",TargetName((Affix)var,"_")," = ",InitialValue,";");
               }
               break;
            case AD.transput:
               if (isVar) {
                  emitter.Emitnl(DataType," ",TargetName((Var)var,"_")," = ",TargetName((Var)var),";");
               } else {
                  emitter.Emitnl(DataType," ",TargetName((Affix)var,"_")," = ",TargetName((Affix)var),";");
               }
               break;
         }
      }

