      private void ConditionalWrapperStart(Algorithm called) {
         if (called.CanFail) {
            emitter.Emit("if (");
            ifDepth++;
            IncrementIndent();
         }
      }
      private void ConditionalWrapperEnd(Algorithm called) {
         if (called.CanFail) {
            emitter.Emit(") {");
         }
      }



