}

<#
.SYNOPSIS
   Update the progress of a step in the progress plan.
#>
function Update-StepProgress([string]$StepId,[string]$Status) {
   if (-not $script:ProgressPlan.ContainsKey($StepId)) { return }

   [double]$elapsedSeconds = [Math]::Max(((Get-Date) - $script:ProgressStartTime).TotalSeconds, 1)
   [double]$remainingWeight = [Math]::Max($script:ProgressTotalWeight - $script:ProgressCompletedWeight, 0)
   [double]$percentComplete = if ($script:ProgressTotalWeight -gt 0) {
      [Math]::Round((100.0 * $script:ProgressCompletedWeight) / $script:ProgressTotalWeight, 1)
   } else {
      0
   }

   [int]$secondsRemaining = if ($script:ProgressCompletedWeight -gt 0) {
      [int][Math]::Ceiling(($elapsedSeconds / $script:ProgressCompletedWeight) * $remainingWeight)
   } else {
      -1
   }

   Write-Progress -Activity "Publish CDL2" -Status $Status -PercentComplete $percentComplete -SecondsRemaining $secondsRemaining
}

<#
.SYNOPSIS
   Mark a progress step as complete in the progress plan.
#>
function Complete-ProgressStep([string]$StepId) {
   if ($script:ProgressPlan.ContainsKey($StepId)) {
      $script:ProgressCompletedWeight += [double]$script:ProgressPlan[$StepId]
   }
}

