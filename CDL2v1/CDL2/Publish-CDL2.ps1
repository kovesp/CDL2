   .PARAMETER OS
   The operating system(s) to generate the lab for. Default is both Windows and Linux.
   .PARAMETER NoDeploy
   Skip copying the build to the WSL and Windows test locations. Default is to copy the build.
   .PARAMETER KeepPDBs
   Keep the PDB files in the zip file. Default is to remove the PDB files prior to zipping.
   .PARAMETER UpdateDB
   Update the sample lab database in the WSL test location. Default is to NOT update the database if it exists.
   .PARAMETER Version
