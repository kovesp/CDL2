   if ($VersionInfo.IsUpdate)        { Write-Host -ForegroundColor Cyan "Versioning to:" -NoNewline; Write-Host -ForegroundColor Blue $VersionInfo.Version }
   [string]$buildType = if ($NoDeploy) { "Building for" } else { "Building for and deploying to" }
   if (-not $NoBuild)            { Write-Host -ForegroundColor Cyan "$buildType`: " -NoNewline; Write-Host -ForegroundColor Blue ($OS -join " and ") }
   if ($VersionInfo.IsReleaseCreateSkip) { Write-Host -ForegroundColor Yellow "Release already exists for "$($VersionInfo.ReleaseTag)"; skipping release creation." }
   if ($VersionInfo.IsReleaseCreate) { 
      Write-Host -ForegroundColor Cyan "Releasing with name: " -NoNewline; Write-Host -ForegroundColor Blue $VersionInfo.ReleaseName
      if ($Show -contains 'ReleaseNotes') { 
         Write-Host -ForegroundColor Cyan "      ... and notes:"
         foreach ($notesLine in $VersionInfo.ReleaseNotes -split "`n") { Write-Host -ForegroundColor Blue "   $notesLine" }
      }
   }
   Write-Host -ForegroundColor Yellow "Continue (y/n) " -NoNewline
   if ((Read-Host).ToLower() -ne "y") {
      Write-Host -ForegroundColor Yellow "Aborting."
      exit 0
   }
   
   Update-StepProgress "0" "Step 0. Starting ..."

   ##########################
   # Step 1. Update version #
   ##########################

   if ($VersionInfo.IsUpdate) {
      if ($WhatIfPreference) {
         Write-Host -ForegroundColor Yellow "WhatIf: Updating version from $($VersionInfo.PreviousVersion) to $($VersionInfo.Version) by creating and pushing git tag $($VersionInfo.Version)"
      } else {
         Update-StepProgress "1" "Step 1. Updating version from $($VersionInfo.PreviousVersion) to $($VersionInfo.Version) ..."
         Invoke-Git { git tag $($VersionInfo.Version) }
         Invoke-Git { git push origin $($VersionInfo.Version) } { git tag -d $($VersionInfo.Version) }
         Complete-ProgressStep "1"
         Write-Host -ForegroundColor Green "Version updated to "$($VersionInfo.Version)" and pushed to GitHub."
      }
   }

   #################
   # Step 2. Build #
   #################

   if ($WhatIfPreference) {
      Write-Host -ForegroundColor Yellow "WhatIf: Building the executables for $($OS -join " and ") and copying files to $targetDir for zipping and deployment."
   } else {
      Remove-Item -Recurse -Force $targetDir -ErrorAction Ignore
      New-Item -ItemType Directory -Force -Path "$targetDir\$targetRoot" -ErrorAction Ignore | Out-Null
      
      if (-not $BuildOnly) {
         Update-StepProgress "2.1" "Step 2.1Copying files $source -> $($targetDir -replace [Regex]::Escape($Env:TMP),"$env:TMP") ..."
         Copy-Files "$targetDir\$targetRoot" $FileMap
         Complete-ProgressStep "2.1"
      }

      New-Item -ItemType Directory -Force -Path $releaseDir -ErrorAction Ignore | Out-Null
      Remove-Item -Force "$releaseDir\*.zip" -ErrorAction Ignore
      if (-not $NoBuild -and $Windows) {
         Update-StepProgress "2.2" "Step 2.2 Publishing CDL2 Lab for Windows..."
         dotnet publish CDL2v1.csproj        -c Release -r win-x64   --self-contained -p:PublishSingleFile=true -o:"$targetDir\$targetRoot\bin\Windows" *> $null
         if ($LASTEXITCODE -ne 0) {
            Write-Error "WINDOWS dotnet publish failed with exit code $LASTEXITCODE"
            exit $LASTEXITCODE
         }
         Complete-ProgressStep "2.2"
         if (-not $KeepPDBs) { Remove-Item -Force "$targetDir\$targetRoot\bin\Windows\*.pdb" -ErrorAction Ignore }
      }
      
      if (-not $NoBuild -and $Linux) {
         Update-StepProgress "2.3" "Step 2.3 Publishing CDL2 Lab for Linux..."
         dotnet publish CDL2v1-Linux.csproj -c Release -r linux-x64 --self-contained -p:PublishSingleFile=true -o:"$targetDir\Linux" *> $null
         if ($LASTEXITCODE -ne 0) {
            Write-Error "LINUX dotnet publish failed with exit code $LASTEXITCODE"
            exit $LASTEXITCODE
         }
         Complete-ProgressStep "2.3"
         if (-not $KeepPDBs) { Remove-Item -Force "$targetDir\Linux\*.pdb" -ErrorAction Ignore }
      }
   }

   ########################
   # Step 3.a Create ZIPs #
   ########################
   if ($WhatIfPreference) {
      Write-Host -ForegroundColor Yellow "WhatIf: Creating zip files and copying to $releaseDir, and deploying to test locations."
   } else {
      Push-Location $targetDir
      Remove-Item -Force "$releaseDir\*" -ErrorAction Ignore

      # Create the Windows only version zip file
      Update-StepProgress "3a.1" "Step 3a.1 Creating Windows only zip file (CDL2-Windows.zip) ..."
      zip -r -9 "$releaseDir\CDL2-Windows.zip" $targetRoot -x "cdl2/bin/Linux/*" *> $null
      Complete-ProgressStep "3a.1"
      # Write-Host -ForegroundColor Cyan ("{0,2:N0} MiB" -f ((Get-ChildItem -Path "$releaseDir\CDL2-Windows.zip").Length/1024/1024))
      
      # Copy the Linux directory to the target to create the combined version zip file.
      Update-StepProgress "3a.2" "Step 3a.2 Creating combined zip file (CDL2.zip) ..."
      Move-Item -Force "$targetDir\Linux\*" "$targetDir\$targetRoot\bin\Linux"
      zip -r -9 "$releaseDir\CDL2.zip" $targetRoot *> $null
      Complete-ProgressStep "3a.2"
      # Write-Host -ForegroundColor Cyan ("{0,2:N0} MiB" -f ((Get-ChildItem -Path "$releaseDir\CDL2.zip").Length/1024/1024))
      
      # Remove the Windows directory to create the Linux only version zip file.
      Update-StepProgress "3a.3" "Step 3a.3 Creating Linux only zip file (CDL2-Linux.zip) ..."
      Remove-Item -Recurse -Force "$targetDir\$targetRoot\bin\Windows" -ErrorAction Ignore
      zip -r -9 "$releaseDir\CDL2-Linux.zip" $targetRoot *> $null
      Complete-ProgressStep "3a.3"
      # Write-Host -ForegroundColor Cyan ("{0,2:N0} MiB" -f ((Get-ChildItem -Path "$releaseDir\CDL2-Linux.zip").Length/1024/1024))

      # Build a zip from just the docs here.
      Update-StepProgress "3a.4" "Step 3a.4 Creating Docs zip file (CDL2-Docs.zip) ..."
      zip -r -9 "$releaseDir\CDL2-Docs.zip" "$targetRoot\Docs" *> $null
      Complete-ProgressStep "3a.4"
      # Write-Host -ForegroundColor Cyan ("{0,2:N0} MiB" -f ((Get-ChildItem -Path "$releaseDir\CDL2-Docs.zip").Length/1024/1024))
      
      Update-StepProgress "3a.5" "Step 3a.5 Adding release notes and changes to the release directory ..."
      Copy-Item "$targetDir\CDL2\_README","$targetDir\CDL2\_CHANGES" $releaseDir -Force
      Complete-ProgressStep "3a.5"

      Pop-Location   
   }

   if ($BuildOnly) {
      Write-Progress -Activity "Publish CDL2" -Completed
      Write-Host -ForegroundColor Green "`nBuildOnly specified. Skipping zipping, deployment and release if any."
      exit 0
   }

   ###################
   # Step 3.b Deploy #
   ###################
   if ($WhatIfPreference) {
      Write-Host -ForegroundColor Yellow "WhatIf: Deploying the builds to the test locations (WSL: $Linux, Windows: $Windows) and copying the publish script to the Visual Studio project directory for GitHub."
   } else {
      if (-not $NoDeploy -and $Linux) {
         Update-StepProgress "3.b.1" "Step 3.b.1 Copying Linux build to WSL test location ($WSLDir) and making it executable ..."
         Copy-Item -Force "$releaseDir\CDL2-Linux.zip" $WSLTarget
         WSL -d $WSLDistro unzip -o "$WSLDir/CDL2-Linux.zip" -d $WSLDir *> $null
         [string]$WSLBin = "$WSLDir/cdl2/bin/Linux"
         WSL -d $WSLDistro chmod +x "$WSLBin/cdl2-lab" "$WSLBin/cdl2c" "$WSLBin/CDL2v1-Linux"
         Complete-ProgressStep "3.b.1"
         Remove-Item -Recurse -Force "$targetDir\$targetRoot\bin\Windows" -ErrorAction Ignore
         # Copy the sample lab db to the WSL test location if it doesn't already exist, or if the UpdateDB flag is set.
         if ($UpdateDB || -not (Test-Path "$WSLDistroDir$WSLDir/$sampleDBLocation")) {
            Update-StepProgress "3.b.1.db" "Step 3.b.1 Updating sample lab database in WSL test location ($WSLDistroDir$WSLDir/$sampleDBName) ..."
            WSL -d $WSLDistro cp -f "$WSLDir/$sampleDBLocation" $WSLDir
            Complete-ProgressStep "3.b.1.db"
         }
      }
      
      if (-not $NoDeploy -and $Windows) {
         Update-StepProgress "3.b.2" "Step 3.b.2 Copying Windows build to test location ($WindowsTarget) ..."
         # New-Item -ItemType Directory -Force -Path "$WindowsTarget\$targetDir" -ErrorAction Ignore | Out-Null
         Expand-Archive -Path "$releaseDir\CDL2-Windows.zip" -DestinationPath $WindowsTarget -Force
         Copy-Item -Force "$releaseDir\CDL2-Windows.zip" $WindowsTarget\$targetRoot
         Complete-ProgressStep "3.b.2"
         
         # Copy the sample lab db to the Windows test location if it doesn't already exist, or if the UpdateDB flag is set.
         if ($UpdateDB -or -not (Test-Path "$WindowsTarget$targetRoot\$sampleDBName")) {
            Update-StepProgress "3.b.2.db" "Step 3.b.2 Updating sample lab database in Windows test location ($WindowsTarget$targetRoot\$sampleDBName) ..."
            Copy-Item "$WindowsTarget$sampleDB" "$WindowsTarget$targetRoot\" -Force -ErrorAction Ignore
            Complete-ProgressStep "3.b.2.db"
         }
      }

      if ($Script -eq "Update") {
         Update-Script
      }
   }

   
   ###################
   # Step 4. Release #
   ###################
   if ($WhatIfPreference -and $VersionInfo.IsReleaseCreate) {
      Write-Host -ForegroundColor Yellow "WhatIf: Creating GitHub release `"$($VersionInfo.ReleaseName)`" with the generated zip files attached."
   } elseif ($VersionInfo.IsReleaseCreate) {
      [string[]]$releaseFiles = @(Get-ChildItem -Path $releaseDir -File | ForEach-Object FullName)
      [string]$preReleaseFlag = if ($PreRelease) { "Pre-release" } else { "release" }
      Update-StepProgress "4" "Step 4. Creating GitHub $preReleaseFlag `"$($VersionInfo.ReleaseName)`" with $($releaseFiles.Count) generated zip files attached ..."
      Invoke-Git { git tag -d $($VersionInfo.Version) *> $null }
      Invoke-Git { git push --delete origin $($VersionInfo.Version) *> $null }
      Invoke-Git { git tag $($VersionInfo.ReleaseTag) *> $null }
      Invoke-Git { git push origin $($VersionInfo.ReleaseTag) *> $null } { git tag -d $($VersionInfo.ReleaseTag) *> $null }
      [string]$preReleaseFlag = if ($PreRelease) { "--prerelease" } else { '' }
      $releaseURL = gh release create $($VersionInfo.ReleaseTag) @releaseFiles --title "$($VersionInfo.ReleaseName)" --notes "$($VersionInfo.ReleaseNotes)" $preReleaseFlag 2> $null
      if ($LASTEXITCODE -eq 0) {
         Complete-ProgressStep "4"
         Write-Progress -Activity "Publish CDL2" -Completed
         Write-Host -ForegroundColor Green "Release `"$($VersionInfo.ReleaseName)`" created successfully at $releaseURL"
         if (-not [string]::IsNullOrWhiteSpace($releaseURL)) {
            Start-Process $releaseURL
         }
      } else {
         Write-Error "GitHub release creation failed with exit code $LASTEXITCODE"
         exit $LASTEXITCODE
      }
   }

   Write-Progress -Activity "Publish CDL2" -Completed
} finally {
   Pop-Location
}