<#
.SYNOPSIS
   Copy the files in $map to the target given by $dst. The keys of $map are the file names.
   The value of $map is a hashtable with the same structure as $FileMap.
.PARAMETER dst
   The target directory to copy the files to.
.PARAMETER map
   The hashtable that maps file names to their source directories relative to $source. 
   The value may be the empty string (use $source\$targetRoot), or the directory of the file relative to $source.
#>
function Copy-Files([string]$dst,[Hashtable]$map) {
   if ($WhatIfPreference) {
      Write-Host -ForegroundColor Yellow "WhatIf: Copying files in file map to $dst"
   } else {
      [string]$dstDir = $dst -replace [regex]::escape("$targetDir\$targetRoot"),''
      foreach ($fn in $map.Keys | Sort-Object) {
         $src = $map[$fn]
         if ($src -is [string]) {
            [string]$srcPath = ''
            if ($src -eq '') {
               $srcPath = Join-Path $source "$targetRoot\$fn"
            } else {
               $srcPath = Join-Path $source "$(if ($src -eq '.') { '' } else { $src })\$fn"
            }
            $fileName = $srcPath -replace "$([Regex]::Escape($source))\\",''
            if ($fileName.StartsWith($targetRoot)) {
               $fileName = $fileName -replace "^$targetRoot","$targetRoot$dstDir"
            }
            if ($Show -contains 'Files') { Write-Host -ForegroundColor Yellow "   $filename" }
            New-Item -ItemType Directory -Force -Path $dst -ErrorAction Ignore | Out-Null
            Copy-Item $srcPath $dst -Force
         } else {
            New-Item -ItemType Directory -Force -Path "$dst\$fn" -ErrorAction Ignore | Out-Null
            Copy-Files "$dst\$fn" $map[$fn]
         } 
      }
   }  
}

<#
.SYNOPSIS
   Convert a result to a normalized format. All forms of empty results (null, empty string, whitespace string,
   empty array, array of only empty strings) are normalized to null.
.PARAMETER result
   The result to normalize.
#>
function ConvertTo-NormalizedResult($result) {
   if ($null -eq $result) { return $null }

   if ($result -is [string]) {
      if ([string]::IsNullOrWhiteSpace($result)) { return $null}
      return $result
   }

   if ($result -is [array]) {
      $usable = @($result | Where-Object {
         if ($_ -is [string]) { return -not [string]::IsNullOrWhiteSpace($_) }
         return $null -ne $_
      })
      if ($usable.Count -eq 0) {
         return $null
      }
      return $usable
   }

   return $result
}

<#
.SYNOPSIS
   Expand tab characters to spaces using fixed tab stops.
.PARAMETER text
   The input text that may contain tab characters.
.PARAMETER TabWidth
   The tab-stop width to use when expanding tabs.
#>
function Convert-TabsToSpaces([string]$text,[int]$TabWidth=4) {
   if ($null -eq $text) { return $null }

   [System.Text.StringBuilder]$builder = [System.Text.StringBuilder]::new()
   [int]$column = 0
   foreach ($ch in $text.ToCharArray()) {
      if ($ch -eq "`t") {
         [int]$spacesToNextTabStop = $TabWidth - ($column % $TabWidth)
         [void]$builder.Append(' ' * $spacesToNextTabStop)
         $column += $spacesToNextTabStop
      } else {
         [void]$builder.Append($ch)
         $column++
      }
   }
   return $builder.ToString()
}

<#
.SYNOPSIS
   Invoke a Git command and handle errors.
.PARAMETER gitCommand
   The Git command to execute.
.PARAMETER errorHandler
   A script block to execute if the Git command fails. It is meant to undo a possible previous git command.
.PARAMETER Force
   Force the execution of the Git command even if -WhatIf is specified.
#>
function Invoke-Git([scriptblock]$gitCommand,[scriptblock]$errorHandler=$null,[switch]$Force) {
   [string]$operation = (($gitCommand.ToString().Trim() -split "\s+") | Select-Object -First 2) -join " "
   if ($WhatIfPreference -and -not $Force) {
      Write-Host -ForegroundColor Yellow "WhatIf: $operation"
   } else {
      $res = & $gitCommand
      if ($LASTEXITCODE -ne 0) {
         if ($null -ne $errorHandler) { 
            Write-Error "$operation failed with exit code $LASTEXITCODE, performing error handling operations"
            & $errorHandler 
         } else {
            Write-Error "$operation failed with exit code $LASTEXITCODE"
         }
         exit $LASTEXITCODE
      }
      return (ConvertTo-NormalizedResult $res)
   }
}

# Process the versioning and release parameters. 
# If versioning is requested, the latest tag is retrieved and the new version number is calculated based on the specified type (Major or Minor).
# Note this is processed regardless of whether -WhatIf was specified.
<#
.SYNOPSIS
   Process the versioning and release parameters. 
   If versioning is requested, the latest tag is retrieved and the new version number is calculated based on the specified type (Major or Minor).
   Note this is processed regardless of whether -WhatIf was specified because it uses -Force on Invoke-Git calls.
#>
function Get-Version() {
   [string]$latestTag = (Invoke-Git { git describe --tags --abbrev=0 --match "v[0-9]*.[0-9]*" } -Force)
   if ($latestTag -match "^v(\d+)\.(\d+)(R?)") {
      [int]$major               = [int]$matches[1]
      [int]$minor               = [int]$matches[2]
      [bool]$isRelease          = $matches[3] -eq "R"    
      [bool]$isCurrentRelease   = $isRelease -and $null -ne (Invoke-Git { git tag --points-at HEAD --list $latestTag } -Force) # Is the latest tag attached to the HEAD commit?
      [string]$curVersion       = "v$major.$minor"
      if ($Release -eq "Undo" -and -not $isRelease) {
         Write-Error "Cannot undo release because the HEAD commit is not a release"
         exit 1
      }
      [bool]$isVersionUpdate = $Version -eq "Major" -or $Version -eq "Minor"
      switch ($Version) {
         "Major" { $major++ ; $minor = 0 }
         "Minor" { $minor++ }
      }
      [string]$newVersion = "v$major.$minor"
      
      $lastCommit = (Invoke-Git { git log -1 --pretty=format:"%h - %s (%ci)" } -Force)
      # Get a version tag that points at HEAD (the last commit), if one exists.
      $lastTag = (Invoke-Git { git tag --points-at HEAD --list "v[0-9]*.[0-9]*" --sort=-v:refname } -Force | Select-Object -First 1)
      [bool]$headNotVersioned = [string]::IsNullOrWhiteSpace($lastTag)
      if ($headNotVersioned) {
         if (-not $isVersionUpdate -and $Release -eq "Create") {
            Write-Error "Cannot create release because the HEAD commit is not versioned. Please specify a version update with the -Version parameter."
            exit 1
         }
         $lastTag = "UNVERSIONED" 
      }
      return @{
         Major                  = $major                                                     # The current major version, if updating, then the next major version
         Minor                  = $minor                                                     # The current minor version, if updating, then the next minor version
         PreviousVersion        = $curVersion                                                # The previous version after updating (i.e, the current version)
         Version                = $newVersion                                                # The new version to update to, or the current version if not updating
         ReleaseTag             = "${newVersion}R"                                           # The release tag to create, which is the version tag with an R suffix
         IsUpdate               = $isVersionUpdate                                           # Is a version update requested?
         IsVersionUndo          = $Version -eq "Undo"                                        # Is a version undo requested?
         IsReleaseCreate        = $Release -eq "Create" -and -not $isCurrentRelease          # Is a release creation requested when the current HEAD commit is not already a release)?
         IsReleaseCreateSkip    = $Release -eq "Create" -and $isCurrentRelease               # Is a release creation requested when the current HEAD commit is already a release?
         IsReleaseUndo          = $Release -eq "Undo"                                        # Is a release undo requested?
         IsRelease              = $isRelease                                                 # Is the latest version tag a release?
         IsCurrentRelease       = $isCurrentRelease                                          # Is the current HEAD commit already tagged with the latest version tag?
         ReleaseName            = ''                                                         # The name of the release to create. It will be supplied by -Get-ReleaseNotes.
         ReleaseNotes           = ''                                                         # The release notes to include in the release description. It will be supplied by -Get-ReleaseNotes.
         PublishMessage         = "$lastTag - $lastCommit"                                   # The message to include in the query to the user describing what will be done.
         UnversionedHEAD        = $headNotVersioned                                          # Is the HEAD commit unversioned (i.e., does not have a version tag pointing at it)?
         UncommittedChanges     = $null -ne (Invoke-Git { git status --porcelain } -Force)   # Are there uncommitted changes in the repository?
      }
   } else {
      Write-Error "Latest tag "$latestTag" does not match the expected pattern "vM.m" or "vM.mR''
      exit 1
   }
}

<#
.SYNOPSIS
   Load the release notes extracted from the _CHANGES file into $VersionInfo.ReleaseNotes.
#>
function Get-ReleaseNotes() {
   if ($VersionInfo.IsReleaseCreate) {
      [string[]]$changesLines = Get-Content "$source\_CHANGES"
      if ($changesLines[0] -match '^Changes in release (\d+\.\d+)') {
         $bounds = (0..($changesLines.Count - 1)).Where({ $changesLines[$_] -match '^Changes in release' }, 'First', 2)
         if ($bounds[0]+2 -gt $bounds[1]) {
            Write-Error "The _CHANGES file does not contain a section for changes for the latest version or there is no title line.Please update the _CHANGES file before creating the release."
            exit 1
         }
         $VersionInfo.ReleaseName = $changesLines[$bounds[0]+2].Trim() # The line after the title line is used as the release name

         [string[]]$releaseDescription = $changesLines[($bounds[0]+3)..($bounds[1] - 1)] # The lines after the release name line until the next title line are used as the release description
         while ($releaseDescription.Count -gt 0 -and [string]::IsNullOrWhiteSpace($releaseDescription[0])) {  $releaseDescription = $releaseDescription[1..($releaseDescription.Count - 1)] }
         while ($releaseDescription.Count -gt 0 -and [string]::IsNullOrWhiteSpace($releaseDescription[$releaseDescription.Count-1])) {  $releaseDescription = $releaseDescription[0..($releaseDescription.Count - 2)] }
         $releaseDescription = $releaseDescription | ForEach-Object { Convert-TabsToSpaces $_ 3 } # Replace tabs with spaces using 3-column tab stops for consistent indentation measurement
         [int]$minIndent = ($releaseDescription | Where-Object { $_.Length -gt 0 } | Foreach-Object { [void]($_ -match "^( *)"); $matches[1].Length  } | Measure-Object -Minimum).Minimum
         $releaseDescription = $releaseDescription | ForEach-Object { if ($_.Length -gt 0) { $_.Substring($minIndent) } else { '' } }
         $VersionInfo.ReleaseNotes = $releaseDescription -join "`n"
      } else {
         Write-Error "The _CHANGES file does not contain a section for changes for any version. Please update the _CHANGES file before creating the release."
         exit 1
      }
   }
}

<#
.SYNOPSIS
   Update the script in the Visual Studio project directory if this version of the script is newer than the one in the project directory.
#>
function Update-Script() {
   function lrw($fn) { Get-ChildItem $fn | Select-Object -ExpandProperty LastWriteTime }
   [string]$scriptName = $PSCommandPath | Split-Path -Leaf
   if ((lrw $PSCommandPath) -gt (lrw "$VSProjectDir\$scriptName")) {
      # This version of the script is newer than the one in the Visual Studio project directory, so copy it over.
      # This ensures that the latest version of the script is always in the project directory for GitHub.
      # Make it R/O there to prevent inadvertent update.
      Write-Host -ForegroundColor Green "`nCopying publish script to Visual Studio project directory for GitHub ..."
      Copy-Item -Force $PSCommandPath $VSProjectDir
      Set-ItemProperty -Path "$VSProjectDir\$scriptName" -Name IsReadOnly -Value $true
   }
}

<#
