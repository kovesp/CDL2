<#
.SYNOPSIS
Generate a Windows and a Linux executable for the CDL2 lab and package for Linux.
.DESCRIPTION
   The script copies required files for distribution and generates 3 zip files:
   * CDL2-Windows.zip: Contains the Windows executables and all other files, but not the Linux executables.
   * CDL2-Linux.zip: Contains the Linux executables and all other files, but not the Windows executables.
   * CDL2.zip: Contains both the Windows and Linux executables and all other files.
   
   The script also copies itself to the Visual Studio project directory so it is pushed to GitHub.

   IMPORTANT:
   Do not edit this file in the Visual Studio project directory. Edit the file in the source directory and 
   then run the script to copy it to the project directory. The file in the project directory
   is read-only to prevent accidental edits.
   
   .INPUTS
   WHen generating a release, the script expect to read the the $source\_UPDATES files. THe first line will contain the title of the release,
   and the following lines will contain the release notes. The script will add these to the front of the $source\_CHANGES file together with
   the release number.
   
   .PARAMETER NoBuild
   Skip building the executables. Default is to build the executables.
   .PARAMETER BuildOnly
   Only build the executables. Default is to build and deploy. Use OS to build only one or both.
   .PARAMETER OS
   The operating system(s) to generate the lab for. Default is both Windows and Linux.
   .PARAMETER NoDeploy
   Skip copying the build to the WSL and Windows test locations. Default is to copy the build.
   .PARAMETER KeepPDBs
   Keep the PDB files in the zip file. Default is to remove the PDB files prior to zipping.
   .PARAMETER UpdateDB
   Update the sample lab database in the WSL test location. Default is to NOT update the database if it exists.
   .PARAMETER Version
   Update the version number of the app using git tag vM.m unless the value is None (the default).
   Finds the latest tag that matches the pattern "vM.m" and increments the version number based on the specified
   type (Major or Minor). Default is to increment the Minor version number.
   When this parameter is not None, only versioning will be done.
   A value of Undo can be used to undo the last version update by deleting the latest tag.
   Use with caution, and only if you are sure that the latest tag is the one created by the last version update.
   The release artifacts will be built in the directory $releaseDir which should be outside the source directory.
   .PARAMETER Release
   If the value is Create, a GitHub release with the name given by the Name parameter will be created from the latest version tag with the generated zip files attached.
     * The HEAD commit must be tagged with a version tag for the release to be created, OR versioning must also be requested to create a new version tag.
   If the value is 'Undo', the last release will be removed from GitHub.
     * The version tag is changed back to a version tag by removing the R.
   .PARAMETER PreRelease
   If specified, the release will be marked as a pre-release.
   .EXAMPLE
   .\Publish-CDL2.ps1 -Version Minor
   This command increments the minor version number of the latest version tag and pushes the new tag to GitHub. 
   For example, if the latest tag is v1.2, it creates and pushes the new tag v1.3.
   .EXAMPLE
   .\Publish-CDL2.ps1 -Release Create -Name "Alpha test"
   This command creates a GitHub release named "Alpha test" from the latest version tag and attaches the generated zip files to the release.
   .EXAMPLE
   .\Publish-CDL2.ps1 -Version Minor -Release Create -Name "Beta Test"
   This command increments the minor version number of the latest version tag, pushes the new tag to GitHub, builds the release artifacts,
   and creates a GitHub release named "Beta Test" from the new version tag with the generated zip files attached.
   #>   
   
   #cspell:ignore czvf labc kovesp Linq

